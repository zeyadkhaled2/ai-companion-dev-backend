import { prisma } from '../../shared/database/prisma';
import { comparePassword, generateToken, hashPassword } from './auth.service';
import { Request, Response } from 'express';
import { AuthRequest } from '../../shared/middleware/auth.middleware';

export async function register(req: Request, res: Response) {
  const { email, password, name, photo } = req.body;
  if (photo !== undefined && !validPhoto(photo)) {
    res.status(400).json({ message: 'Choose a JPEG photo smaller than 300 KB' });
    return;
  }

  if (!email || !password || !name) {
    res.status(400).json({ message: 'Email, password, and name are required' });
    return;
  }

  const existingUser = await prisma.user.findUnique({ where: { email } });

  if (existingUser) {
    res.status(409).json({ message: 'Email already in use' });
    return;
  }

  const hashedPassword = await hashPassword(password);

  const newUser = await prisma.user.create({
    data: {
      email,
      password: hashedPassword, // key matches schema field, value is your hashed variable
      name,
      photo,
    },
  });

  const token = generateToken(newUser.id);

  res.status(201).json({
    token,
    user: { id: newUser.id, email: newUser.email, name: newUser.name, photo: newUser.photo },
  });
}

export async function login(req: Request, res: Response) {
  const { email, password } = req.body;

  if (!email || !password) {
    res.status(400).json({ message: 'Email and password are required' });
    return;
  }
  const loginUser = await prisma.user.findUnique({ where: { email } });
  if (!loginUser) {
    res.status(401).json({ message: 'Email or password is incorrect' });
    return;
  }
  const passwordMatch = await comparePassword(password, loginUser.password);
  if (passwordMatch) {
    const token = generateToken(loginUser.id);
    res.status(200).json({
      token,
      user: {
        id: loginUser.id,
        email: loginUser.email,
        name: loginUser.name,
        photo: loginUser.photo,
      },
    });
  } else {
    res.status(401).json({ message: 'Email or password is incorrect' });
    return;
  }
}
export async function getProfile(req: AuthRequest, res: Response) {
  if (!req.userId) {
    res.status(401).json({ message: 'Not authenticated' });
    return;
  }

  const user = await prisma.user.findUnique({
    where: { id: req.userId }, // now narrowed to `string`
    select: { id: true, email: true, name: true, createdAt: true, photo: true },
  });

  res.status(200).json({ user });
}
// Only bounded JPEG data URLs generated by the photo editor are accepted.
export function validPhoto(photo: unknown): boolean {
  if (photo === null) return true;
  if (typeof photo !== 'string' || photo.length > 410000) return false;
  const match = /^data:image\/jpeg;base64,([A-Za-z0-9+/]+={0,2})$/.exec(photo);
  if (!match?.[1]) return false;
  const bytes = Buffer.from(match[1], 'base64');
  return bytes.length <= 307200 && bytes[0] === 255 && bytes[1] === 216 && bytes[2] === 255;
}

export async function updateProfilePhoto(req: AuthRequest, res: Response) {
  if (!req.userId) {
    res.status(401).json({ message: 'Not authenticated' });
    return;
  }
  if (!validPhoto(req.body.photo)) {
    res.status(400).json({ message: 'Choose a JPEG photo smaller than 300 KB' });
    return;
  }
  const user = await prisma.user.update({
    where: { id: req.userId },
    data: { photo: req.body.photo },
    select: { id: true, email: true, name: true, photo: true },
  });
  res.json({ user });
}
